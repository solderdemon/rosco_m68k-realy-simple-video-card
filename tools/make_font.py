def table():
    rows = {}
    for line in GLYPHS.strip('\n').splitlines():
        ch, cells = line[0], line[2:].split(':')
        assert len(cells) == 8 and all(len(c) == 5 for c in cells), (ch, cells)
        rows[ch] = [sum(1 << (7 - i) for i, p in enumerate(c) if p == '#') for c in cells]
    missing = [chr(c) for c in range(32, 127) if chr(c) not in rows]
    assert not missing, f'no glyph for {missing}'
    return [rows[chr(c)] for c in range(32, 127)]


def show(t):
    for c, glyph in zip(range(32, 127), t):
        print(f'--- {chr(c)} ({c}) ---')
        for r in glyph:
            print(''.join('#' if r >> (7 - i) & 1 else '.' for i in range(8)))


t = table()
if '--show' in sys.argv:
    show(t)
else:
    body = ['/* Generated by tools/make_font.py -- edit the pictures there, not this file. */',
            '#include <stdint.h>', '',
            '/* ASCII 32..126, eight rows per glyph, bit 7 = leftmost pixel. */',
            'const uint8_t video_font8x8[95][8] = {']
    for c, glyph in zip(range(32, 127), t):
        name = {0x27: "'", 0x5C: '\\\\'}.get(c, chr(c))
        body.append('    { ' + ', '.join(f'0x{r:02X}' for r in glyph) + f" }},   /* '{name}' */")
    body += ['};', '']
    (ROOT / 'code' / 'software' / 'font8x8.c').write_text('\n'.join(body), encoding='utf-8')
    print(f'software/font8x8.c: {len(t)} glyphs')
